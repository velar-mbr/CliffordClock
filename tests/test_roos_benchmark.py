def test_structural_two_ion_enhancement_ratio_is_24_over_5() -> None:
    ratio = roos_benchmark.structural_two_ion_enhancement_ratio()
    np.testing.assert_allclose(ratio, 24.0 / 5.0, rtol=0, atol=1e-12)


def test_structural_ratio_independent_of_applied_gradient_magnitude() -> None:
    """The ratio is a pure structure constant -- must be identical at two
    different applied gradients (both `Delta_E_Q` terms are exactly linear
    in the gradient, so it cancels in the ratio)."""
    ratio_at_10 = roos_benchmark.structural_two_ion_enhancement_ratio(10.0)
    ratio_at_45 = roos_benchmark.structural_two_ion_enhancement_ratio(45.0)
    np.testing.assert_allclose(ratio_at_10, ratio_at_45, rtol=0, atol=1e-12)
    np.testing.assert_allclose(ratio_at_10, 24.0 / 5.0, rtol=0, atol=1e-12)


def test_structural_ratio_uses_real_quadrupole_mj_factor_values() -> None:
    """Cross-check against a direct, independent call to
    `quadrupole_mj_factor` -- confirms the sum
    `f(5/2)+f(3/2)-f(1/2)-f(1/2) = -2.4` (dossier section 6's stated
    bracket) really is what drives the ratio, not a coincidence."""
    from cliffordclock.integrator.omega import quadrupole_mj_factor

    j = 2.5
    bracket = (
        quadrupole_mj_factor(j, -2.5)
        + quadrupole_mj_factor(j, 1.5)
        - quadrupole_mj_factor(j, -0.5)
        - quadrupole_mj_factor(j, -0.5)
    )
    np.testing.assert_allclose(bracket, -2.4, rtol=0, atol=1e-12)
    # single-ion |-5/2> factor is quadrupole_mj_factor(j, -2.5) = -1;
    # doubled-gradient two-ion energy over undoubled single-ion energy:
    # (bracket * 2) / (-1) = 24/5.
    np.testing.assert_allclose(
        (bracket * 2.0) / quadrupole_mj_factor(j, -2.5), 24.0 / 5.0, rtol=0, atol=1e-12
    )


