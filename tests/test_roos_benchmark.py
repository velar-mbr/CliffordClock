def test_predicted_slope_uses_real_quadrupole_shift_joules_no_hand_math() -> None:
    """The slope must come from `quadrupole_shift_joules` itself (via
    `two_ion_hbar_delta1_joules`), not a reimplementation -- verified by
    an independent direct cross-call."""
    import jax.numpy as jnp

    from cliffordclock.constants import PLANCK_H
    from cliffordclock.integrator.omega import quadrupole_shift_joules

    theta_au = 1.917
    g_vmm2 = 30.0
    doubled_g_si = 2.0 * g_vmm2 * 1.0e6
    grad = jnp.array([[-doubled_g_si / 2, 0, 0], [0, -doubled_g_si / 2, 0], [0, 0, doubled_g_si]])
    axis = jnp.array([0.0, 0.0, 1.0])
    j = 2.5
    e1 = quadrupole_shift_joules(grad, axis, theta_au, j, -2.5) + quadrupole_shift_joules(
        grad, axis, theta_au, j, 1.5
    )
    e2 = quadrupole_shift_joules(grad, axis, theta_au, j, -0.5) + quadrupole_shift_joules(
        grad, axis, theta_au, j, -0.5
    )
    expected_hz_mm2_per_v = abs(float(e1 - e2) / PLANCK_H) / g_vmm2

    actual = roos_benchmark.predicted_slope_hz_mm2_per_v(theta_au, g_vmm2)
    np.testing.assert_allclose(actual, expected_hz_mm2_per_v, rtol=0, atol=0)


