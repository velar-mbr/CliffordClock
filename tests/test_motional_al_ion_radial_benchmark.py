"""Tests for `benchmarks/run_motional_al_ion.py`'s WP32 radial-spectrum-
reconstructed variant (CONVENTIONS.md section 16, WP32;
`cliffordclock.integrator.omega.axial_coulomb_curvature`/
`two_ion_radial_participations`).

Mirrors `tests/test_bbr_benchmark.py`'s regression-pin discipline: import
the benchmark module directly and call its real `run_*_case()` function
(no mocking, no reimplemented arithmetic), pinning the actual engine
output with `np.testing.assert_allclose(..., rtol=..., atol=0)` and an
explicit provenance comment naming how the pin was generated. If this
file's pins and the script's own output ever diverge, that is a finding
to report (a registry/engine change, or a stale pin), never something to
silently reconcile by re-pinning without investigating why.

WP30/WP31 (`run_motional_al_ion_arithmetic_reproduction_case`/
`run_motional_al_ion_participation_variant_case`) are untouched by WP32 and
already exercised by `tests/test_motional_pivot.py`'s `two_ion_participations`
coverage; this file is WP32-specific.
"""

from __future__ import annotations

import sys
from pathlib import Path

import numpy as np

_BENCHMARKS_DIR = Path(__file__).resolve().parent.parent / "benchmarks"
if str(_BENCHMARKS_DIR) not in sys.path:
    sys.path.insert(0, str(_BENCHMARKS_DIR))

import run_motional_al_ion as motional_benchmark  # noqa: E402


def test_radial_reconstructed_case_coulomb_curvature_pinned() -> None:
    """`c` recovered from Marshall et al.'s axial-COM mode frequency
    (2.16 MHz) at the Al27+/Mg25+ mass ratio. Generated by
    `python benchmarks/run_motional_al_ion.py` (this session):
    `c = 3.976554191127463e-12` N/m; the axial-STR cross-check
    (`c = 3.983457322953556e-12` N/m) agrees to `1.736e-3` relative, the
    frequencies' own ~3-significant-figure reporting precision."""
    case = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()
    np.testing.assert_allclose(
        case.coulomb_curvature_n_per_m, 3.976554191127463e-12, rtol=1e-10, atol=0
    )
    np.testing.assert_allclose(
        case.coulomb_curvature_cross_check_n_per_m, 3.983457322953556e-12, rtol=1e-6, atol=0
    )
    np.testing.assert_allclose(
        case.coulomb_curvature_cross_check_relative_deviation, 1.7360e-3, rtol=1e-3, atol=0
    )


def test_radial_reconstructed_case_bare_frequencies_pinned() -> None:
    """Reconstructed bare (single-ion) radial frequencies, X and Y
    branches, generated by `python benchmarks/run_motional_al_ion.py`
    (this session). The partner ion (Mg25+, lighter) comes out with the
    higher bare frequency on both branches, the disambiguation rule's own
    physical requirement: this test checks that requirement directly,
    not just a pinned number left unchecked."""
    case = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()
    np.testing.assert_allclose(case.bare_frequency_clock_x_hz, 3946771.607526584, rtol=1e-9, atol=0)
    np.testing.assert_allclose(
        case.bare_frequency_partner_x_hz, 4360931.835761294, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(case.bare_frequency_clock_y_hz, 5084690.883277048, rtol=1e-9, atol=0)
    np.testing.assert_allclose(
        case.bare_frequency_partner_y_hz, 5497385.853262768, rtol=1e-9, atol=0
    )
    assert case.bare_frequency_partner_x_hz > case.bare_frequency_clock_x_hz
    assert case.bare_frequency_partner_y_hz > case.bare_frequency_clock_y_hz


def test_radial_reconstructed_case_per_mode_participations_pinned() -> None:
    """Per-mode reconstructed participations, `_MODE_NAMES` order, generated
    by `python benchmarks/run_motional_al_ion.py` (this session). The two
    axial entries are `two_ion_participations`' unchanged closed form (WP31);
    the four radial entries are WP32's reconstruction."""
    case = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()
    expected = {
        "axial_com": 0.5383182958618564,
        "axial_str": 0.4616817041381436,
        "x_com": 0.21383374360296137,
        "x_str": 0.7861662563970391,
        "y_com": 0.1662947736122066,
        "y_str": 0.8337052263877938,
    }
    for entry in case.per_mode:
        np.testing.assert_allclose(
            entry.participation, expected[entry.name], rtol=1e-9, atol=0, err_msg=entry.name
        )
    # Sum rule: each mode-pair's clock-ion participations add to 1.0
    # exactly, for both the (unchanged) axial pair and the (reconstructed)
    # radial pairs.
    np.testing.assert_allclose(
        expected["axial_com"] + expected["axial_str"], 1.0, rtol=0, atol=1e-13
    )
    np.testing.assert_allclose(expected["x_com"] + expected["x_str"], 1.0, rtol=0, atol=1e-13)
    np.testing.assert_allclose(expected["y_com"] + expected["y_str"], 1.0, rtol=0, atol=1e-13)


def test_radial_reconstructed_case_total_pinned() -> None:
    """The reconstructed-participation TOTAL `(P-1)_motional`, generated
    by `python benchmarks/run_motional_al_ion.py` (this session):
    `-5.716945188613549e-18 +/- 1.535e-19`, landing at ~14.0 sigma from
    Marshall et al.'s published `-114.6(3.8)e-19` (`total_kpi_verdict`
    `"NOT MET"`) -- essentially unchanged from WP31's own
    axial-form-approximation total (`-5.759425e-18`, ~14.11 sigma; this
    project's own G11/WP31 record), consistent with this case's own
    `participation_note`: redistributing participation within a
    mode-pair (which sums to 1.0 regardless of the split) does not move
    that pair's own total much, so getting the split right does not by
    itself close a total-level gap this size."""
    case = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()
    np.testing.assert_allclose(
        case.predicted_total_nominal, -5.716945188613549e-18, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_fractional, 1.5350414847485596e-19, rtol=1e-6, atol=0
    )
    assert case.total_bands_overlap is False
    assert case.total_kpi_verdict == "NOT MET"


def test_radial_reconstructed_case_class_is_arithmetic_reproduction() -> None:
    case = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()
    assert case.case_class == "arithmetic_reproduction"


def test_build_wp32_report_and_render_markdown_round_trip() -> None:
    """`build_wp32_report`/`render_wp32_markdown` (the artifact-writing
    path `main()` drives) run end to end and embed the pinned total."""
    report = motional_benchmark.build_wp32_report()
    case = report["marshall_2504_13071_radial_reconstructed_variant_case"]
    np.testing.assert_allclose(
        case["predicted_total_nominal"], -5.716945188613549e-18, rtol=1e-9, atol=0
    )
    markdown = motional_benchmark.render_wp32_markdown(report)
    assert "WP32" in markdown
    assert "NOT MET" in markdown
    assert motional_benchmark.RADIAL_RECONSTRUCTION_CAVEAT in markdown


def test_wp30_wp31_cases_unaffected_by_wp32_addition() -> None:
    """WP32 is purely additive: WP30's single-mass total and WP31's
    axial-form participation-corrected total (both pre-existing, computed
    by functions this change does not touch) must be bit-for-bit unchanged
    from their own pinned values (this project's existing G11/WP31 record)."""
    case = motional_benchmark.run_motional_al_ion_arithmetic_reproduction_case()
    np.testing.assert_allclose(case.predicted_shift_nominal, -1.150871e-17, rtol=1e-6, atol=0)
    assert case.kpi_verdict == "MET"

    participation_case = motional_benchmark.run_motional_al_ion_participation_variant_case()
    np.testing.assert_allclose(
        participation_case.predicted_total_nominal, -5.759424995747776e-18, rtol=1e-9, atol=0
    )
    assert participation_case.total_kpi_verdict == "NOT MET"
