"""Tests for `benchmarks/run_bbr_jila_arithmetic_reproduction.py` (WP20
design item 5, gate edit 8; the project's theory sign-off record (G7), B5) --
the JILA BBR-row **arithmetic-reproduction** benchmark case.

Mirrors `tests/test_benchmarks_loaders.py`'s NPL-case test discipline:
real engine calls (`cliffordclock.integrator.omega.bbr_pivot_perturbation`/
`bbr_pivot_uncertainty`), no mocking, tolerances stated explicitly
(`np.testing.assert_allclose(..., rtol=..., atol=0)`, house doctrine --
never a bare `pytest.approx`). The numbers pinned here are regenerated by
running ``python benchmarks/run_bbr_jila_arithmetic_reproduction.py``; if
this file's pins and that script's output ever diverge, the pin is wrong
or the registry/engine changed -- either way, a finding to report, not to
silently reconcile.
"""

