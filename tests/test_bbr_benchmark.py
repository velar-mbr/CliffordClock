# Label-drift guard (WP20-follow-up review nit 4): the binding G7 B5
# classification language must appear in the user-facing docs themselves, not
# only in the script's own CASE_LABEL constant -- someone editing
# RESULTS.md / README.md / docs/validation.md independently of the
