def test_jila_bbr_temperature_matches_arxiv_2403_10664_verbatim() -> None:
    """`loaders.JILA_BBR_TEMPERATURE_K`: T = 293.282(4) K (arXiv:2403.10664v2
    main-text in-vacuum RTD statement, "20.132(4) degC")."""
    band = loaders.JILA_BBR_TEMPERATURE_K
    np.testing.assert_allclose(band.nominal, 293.282, rtol=0, atol=1e-9)
    np.testing.assert_allclose(band.lo, 293.278, rtol=0, atol=1e-9)
    np.testing.assert_allclose(band.hi, 293.286, rtol=0, atol=1e-9)
    assert band.units == "K"
    assert "2403.10664" in band.citation


def test_jila_bbr_published_shift_matches_table_i_verbatim() -> None:
    """`loaders.JILA_BBR_PUBLISHED_SHIFT`: -48417.2(73) x 10^-19 =
    -4.84172(73) x 10^-15 (Table I "BBR" row, same value as
    `benchmarks/fixtures/jila_2403_10664_table1.csv`)."""
    band = loaders.JILA_BBR_PUBLISHED_SHIFT
    np.testing.assert_allclose(band.nominal, -4.84172e-15, rtol=0, atol=1e-25)
    np.testing.assert_allclose(band.lo, -4.84172e-15 - 7.3e-19, rtol=0, atol=1e-25)
    np.testing.assert_allclose(band.hi, -4.84172e-15 + 7.3e-19, rtol=0, atol=1e-25)
    assert "2403.10664" in band.citation

    # Cross-check against the WP10 fixture's own transcription (both trace
    # to the same Table I row -- must agree to the digit).
    entries = loaders.load_jila_table1(_BENCHMARKS_DIR / "fixtures" / "jila_2403_10664_table1.csv")
    bbr_row = next(e for e in entries if e.shift_name == "BBR")
    np.testing.assert_allclose(band.nominal, bbr_row.shift_fractional, rtol=1e-12, atol=0)


# ---------------------------------------------------------------------------
# run_jila_bbr_arithmetic_reproduction_case -- the core case. Pins the
# actual engine-function output (bbr_pivot_perturbation/bbr_pivot_uncertainty
# called with the pinned Sr87 registry coefficients), not hand arithmetic.
# ---------------------------------------------------------------------------


def test_run_case_uses_only_the_registry_polynomial_no_hand_math() -> None:
    """The case's predicted value must come from `bbr_pivot_perturbation`
    itself, called with the real `Sr87` species object -- not a
    reimplementation. Verified by direct cross-call rather than trusting
    the case's own arithmetic."""
    from cliffordclock.ensemble.species import get_species
    from cliffordclock.integrator.omega import bbr_pivot_perturbation

    case = bbr_benchmark.run_jila_bbr_arithmetic_reproduction_case()
    sr87 = get_species("Sr87")
    expected = bbr_pivot_perturbation(case.temperature_k, sr87)
    np.testing.assert_allclose(case.predicted_shift_nominal, expected, rtol=0, atol=0)


def test_run_case_predicted_nominal_pinned() -> None:
    """Regression pin (WP20 gate edit 8: re-run the dossier Sec.5 arithmetic
    with the PINNED registry polynomial, not the dossier's single-T^6
    quick estimate). Generated by
    `python benchmarks/run_bbr_jila_arithmetic_reproduction.py`
    (2026-08-11): `(P-1)_BBR(Sr87, 293.282 K) = -4.841742511091567e-15`.
    Effective tolerance: `rtol=1e-10` on a ~4.84e-15-magnitude value is an
    absolute tolerance of ~4.84e-25 -- far tighter than any physically
    meaningful digit here, i.e. this pins float64-deterministic
    reproducibility of the polynomial evaluation, not a physics claim."""
    case = bbr_benchmark.run_jila_bbr_arithmetic_reproduction_case()
    np.testing.assert_allclose(
        case.predicted_shift_nominal, -4.841742511091567e-15, rtol=1e-10, atol=0
    )


def test_run_case_temperature_band_pinned_and_ordered() -> None:
    """The T +/- 0.004 K band (G7 sign-off A4#3): two direct
    `bbr_pivot_perturbation` calls at `T -/+ 0.004 K`, not a derivative
    estimate. Higher T -> more negative shift (both the static T^4 term
    and the dynamic coefficients are negative and grow with T), so
    `temperature_band_lo` (more negative) corresponds to `T + 0.004 K`."""
    case = bbr_benchmark.run_jila_bbr_arithmetic_reproduction_case()
    np.testing.assert_allclose(
        case.predicted_shift_temperature_band_lo, -4.8420165996655454e-15, rtol=1e-10, atol=0
    )
    np.testing.assert_allclose(
        case.predicted_shift_temperature_band_hi, -4.8414684346522934e-15, rtol=1e-10, atol=0
    )
    assert case.predicted_shift_temperature_band_lo < case.predicted_shift_nominal
    assert case.predicted_shift_nominal < case.predicted_shift_temperature_band_hi
    # Non-degenerate: an actual band, not a point.
    assert case.predicted_shift_temperature_band_lo < case.predicted_shift_temperature_band_hi


def test_run_case_uncertainty_bands_pinned() -> None:
    """Coefficient-only and combined (coefficient+T) uncertainty bands,
    both from `bbr_pivot_uncertainty` directly (G7 sign-off A4#2-3).
    Generated 2026-08-11: coefficient-only sigma ~6.83e-19, combined sigma
    ~7.36e-19 (both "arithmetic-reproduction fidelity," per the case's
    `case_label`, never "BBR accuracy")."""
    case = bbr_benchmark.run_jila_bbr_arithmetic_reproduction_case()
    np.testing.assert_allclose(
        case.predicted_coefficient_uncertainty_fractional,
        6.831735286985865e-19,
        rtol=1e-9,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_combined_uncertainty_fractional, 7.361027718428797e-19, rtol=1e-9, atol=0
    )
    # Combined must be strictly larger than coefficient-only (an
    # independent, nonzero temperature-uncertainty contribution was
    # actually added in quadrature, not silently dropped).
    assert (
        case.predicted_combined_uncertainty_fractional
        > case.predicted_coefficient_uncertainty_fractional
    )
    np.testing.assert_allclose(
        case.predicted_combined_band_lo,
        case.predicted_shift_nominal - case.predicted_combined_uncertainty_fractional,
        rtol=0,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_combined_band_hi,
        case.predicted_shift_nominal + case.predicted_combined_uncertainty_fractional,
        rtol=0,
        atol=0,
    )


def test_run_case_residual_and_bands_overlap_met() -> None:
    """The headline comparison: residual is a small fraction of the
    combined uncertainty band, and the predicted/published bands overlap
    -- `kpi_verdict = "MET"`. Per the WP20 task's expectation-setting:
    this is expected almost by construction (the registry's dynamic
    polynomial is anchored to JILA's own -153.06 mHz), so a tight
    residual is not a surprising finding."""
    case = bbr_benchmark.run_jila_bbr_arithmetic_reproduction_case()

    np.testing.assert_allclose(case.residual_fractional, -2.2511091567236514e-20, rtol=1e-6, atol=0)
    # The residual is far smaller in magnitude than the combined
    # uncertainty band (arithmetic-reproduction fidelity is much tighter
    # than the physical BBR uncertainty budget) -- a quantitative check,
    # not just "MET".
    assert abs(case.residual_fractional) < case.predicted_combined_uncertainty_fractional

    assert case.bands_overlap is True
    assert case.kpi_verdict == "MET"
    assert case.kpi_verdict not in ("PASS", "FAIL")  # reserved vocabulary this project never uses


