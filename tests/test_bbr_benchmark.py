_REPO_ROOT = Path(__file__).resolve().parent.parent


@pytest.mark.parametrize(
    ("relpath", "required_phrases"),
    [
        (
            "benchmarks/RESULTS.md",
            [
                "arithmetic reproduction of a published standard-formula evaluation",
                "expected almost by construction",
            ],
        ),
        (
            "docs/validation.md",
            ["arithmetic reproduction", "expected almost by construction"],
        ),
        (
            "README.md",
            ["arithmetic reproduction", "weaker class"],
        ),
    ],
)
def test_case_label_present_in_user_facing_docs(relpath: str, required_phrases: list[str]) -> None:
    # Markdown hard-wraps prose, so a phrase can span a line break --
    # collapse all whitespace runs to single spaces before matching.
    raw = (_REPO_ROOT / relpath).read_text(encoding="utf-8")
    text = " ".join(raw.split())
    for phrase in required_phrases:
        assert phrase in text, (
            f"{relpath} lost the binding classification phrase {phrase!r} "
            "(G7 sign-off B5; see this test's header comment)"
        )
