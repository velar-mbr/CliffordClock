def test_constrained_case_fit_parameters_and_residuals_pinned() -> None:
    """The constrained fit's own `(q, alpha, a_x, a_y, a_z)` and its FOUR
    frequency residuals for Marshall et al.'s trap, generated by `python
    benchmarks/run_motional_al_ion.py` (this session). The residuals are
    small (sub-0.1%-relative) but genuinely nonzero -- the fit's own
    falsifiable output, not forced to zero by construction (four
    equations, two unknowns)."""
    case = motional_benchmark.run_motional_al_ion_constrained_floquet_case()
    fit = case.constrained_fit
    np.testing.assert_allclose(fit["mathieu_q"], 0.19064466810368705, rtol=1e-7, atol=0)
    np.testing.assert_allclose(fit["alpha"], 1.6251938469368106, rtol=1e-6, atol=0)
    np.testing.assert_allclose(fit["mathieu_a_x"], -0.00582135682640036, rtol=1e-6, atol=0)
    np.testing.assert_allclose(fit["mathieu_a_y"], 0.0022394106866383003, rtol=1e-5, atol=0)
    np.testing.assert_allclose(fit["mathieu_a_z"], 0.0035819461397620595, rtol=1e-9, atol=0)

    np.testing.assert_allclose(fit["residual_x_com_hz"], -782.6936096530408, rtol=1e-4, atol=0)
    np.testing.assert_allclose(fit["residual_x_str_hz"], 761.9162174556404, rtol=1e-4, atol=0)
    np.testing.assert_allclose(fit["residual_y_com_hz"], -3862.1496889954433, rtol=1e-4, atol=0)
    np.testing.assert_allclose(fit["residual_y_str_hz"], 3721.0150098791346, rtol=1e-4, atol=0)

    # The falsifiable claim itself: residuals are real but small relative
    # to the MHz-scale mode frequencies (the fit is not exact, and is not
    # wildly off either).
    for residual_hz, freq_hz in (
        (fit["residual_x_com_hz"], 4.22e6),
        (fit["residual_x_str_hz"], 3.48e6),
        (fit["residual_y_com_hz"], 5.37e6),
        (fit["residual_y_str_hz"], 4.75e6),
    ):
        assert residual_hz != 0.0
        assert abs(residual_hz / freq_hz) < 0.01


def test_constrained_case_per_mode_ratios_pinned_and_close_to_one() -> None:
    """The constrained fit's per-mode ratios (predicted/published),
    pinned this session, land uniformly close to `1.0`."""
    case = motional_benchmark.run_motional_al_ion_constrained_floquet_case()
    by_name = {m.name: m for m in case.per_mode}

    np.testing.assert_allclose(
        by_name["x_com"].ratio_predicted_over_published, 1.0219542122768865, rtol=1e-6, atol=0
    )
    np.testing.assert_allclose(
        by_name["x_str"].ratio_predicted_over_published, 0.986522360002454, rtol=1e-6, atol=0
    )
    np.testing.assert_allclose(
        by_name["y_com"].ratio_predicted_over_published, 1.0149650151531795, rtol=1e-6, atol=0
    )
    np.testing.assert_allclose(
        by_name["y_str"].ratio_predicted_over_published, 0.9924941425917548, rtol=1e-6, atol=0
    )
    for name in ("x_com", "x_str", "y_com", "y_str"):
        assert abs(by_name[name].ratio_predicted_over_published - 1.0) < 0.03

    # Enhancement genuinely differs between COM and STR of the same axis.
    assert by_name["x_com"].enhancement_clock != by_name["x_str"].enhancement_clock
    assert by_name["y_com"].enhancement_clock != by_name["y_str"].enhancement_clock

    # Axial modes unchanged (enhancement=1.0 identically, predicted
    # frequency equal to measured: a_z is fixed exactly from the axial
    # measurement, not itself fit).
    assert by_name["axial_com"].enhancement_clock == 1.0
    assert by_name["axial_com"].predicted_frequency_hz == by_name["axial_com"].measured_frequency_hz
    assert by_name["axial_str"].enhancement_clock == 1.0


def test_constrained_case_total_and_three_component_budget_pinned_met() -> None:
    """The constrained-fit TOTAL and its THREE separately labeled
    uncertainty components (thermometry, input rounding, model
    structure), pinned this session: `-1.141472229793339e-17`,
    thermometry `+/-3.7628578993311585e-19`, rounding
    `+/-1.0217107815596156e-20`, model structure
    `+/-1.5913571536003457e-19`, combined `+/-4.086802673250257e-19`,
    landing INSIDE Marshall's own published band: `MET`, even with the
    model-structure component counted."""
    case = motional_benchmark.run_motional_al_ion_constrained_floquet_case()

    np.testing.assert_allclose(
        case.predicted_total_nominal, -1.141472229793339e-17, rtol=1e-7, atol=0
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_nbar_fractional,
        3.7628578993311585e-19,
        rtol=1e-5,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_rounding_fractional,
        1.0217107815596156e-20,
        rtol=1e-3,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_model_structure_fractional,
        1.5913571536003457e-19,
        rtol=1e-4,
        atol=0,
    )
    expected_combined = (
        case.predicted_total_uncertainty_nbar_fractional**2
        + case.predicted_total_uncertainty_rounding_fractional**2
        + case.predicted_total_uncertainty_model_structure_fractional**2
    ) ** 0.5
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_combined_fractional, expected_combined, rtol=1e-12, atol=0
    )

    # The model-structure component is real (nonzero) and its own
    # distinct order of magnitude, not degenerate with the other two.
    assert case.predicted_total_uncertainty_model_structure_fractional > 0.0
    assert case.predicted_total_uncertainty_rounding_fractional > 0.0

    assert case.total_bands_overlap is True
    assert case.total_kpi_verdict == "MET"


def test_constrained_case_partner_over_determination_check_implemented() -> None:
    """G17 item 2: the promised partner over-determination check for the
    constrained fit is actually implemented and its numbers pinned this
    session: predicted partner X/Y `4357681.194444927`/
    `5491602.651845002` Hz against WP32's separately-reconstructed
    `4360931.835761294`/`5497385.853262768` Hz, relative deviations
    `-0.0745%`/`-0.1052%`, both sub-1%-relative and TIGHTER than WP34's
    own `-0.45%`/`-0.40%` for the same dataset."""
    case = motional_benchmark.run_motional_al_ion_constrained_floquet_case()

    np.testing.assert_allclose(
        case.bare_frequency_partner_x_predicted_hz, 4357681.194444927, rtol=1e-8, atol=0
    )
    np.testing.assert_allclose(
        case.bare_frequency_partner_y_predicted_hz, 5491602.651845002, rtol=1e-8, atol=0
    )
    np.testing.assert_allclose(
        case.bare_frequency_partner_x_reconstructed_hz, 4360931.835761294, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        case.bare_frequency_partner_y_reconstructed_hz, 5497385.853262768, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        case.partner_x_relative_deviation, -0.0007454006250934471, rtol=1e-5, atol=0
    )
    np.testing.assert_allclose(
        case.partner_y_relative_deviation, -0.001051991177649302, rtol=1e-5, atol=0
    )
    assert abs(case.partner_x_relative_deviation) < 0.01
    assert abs(case.partner_y_relative_deviation) < 0.01
    # Tighter than WP34's own leading-order-exact solve for this dataset.
    assert abs(case.partner_x_relative_deviation) < abs(-0.004543602952041002)
    assert abs(case.partner_y_relative_deviation) < abs(-0.004022004474006867)


