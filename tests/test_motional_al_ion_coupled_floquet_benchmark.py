"""Tests for `benchmarks/run_motional_al_ion.py`'s WP35 coupled-two-ion-
Floquet variants (CONVENTIONS.md section 16, WP35;
`cliffordclock.integrator.omega.coupled_two_ion_floquet_modes`/
`coupled_two_ion_mathieu_parameters`/`constrained_two_ion_mathieu_fit`/
`mathieu_forced_oscillator_enhancement`).

G17 gate fix loop: the CONSTRAINED fit
(`run_motional_al_ion_constrained_floquet_case`) is this WP's own
headline result, genuinely over-determined (four measured frequencies,
two fit parameters, real nonzero residuals). The per-axis solve
(`run_motional_al_ion_coupled_floquet_case`) is kept as a labeled
diagnostic variant: it fits each axis exactly by construction, so its
own near-unity ratios carry no independent evidence on their own.

Mirrors `tests/test_motional_al_ion_exact_floquet_benchmark.py`'s
regression-pin discipline: import the benchmark module directly and call
its real `run_*_case()`/`run_*_check()` functions (no mocking, no
reimplemented arithmetic), pinning the actual engine output with
`np.testing.assert_allclose(..., rtol=..., atol=0)`. If this file's pins
and the script's own output ever diverge, that is a finding to report (a
registry/engine change, or a stale pin), never something to silently
reconcile by re-pinning without investigating why.

WP30-34 are untouched by WP35 and already exercised by their own test
files; this file is WP35-specific. Per this WP's own scope (G17 gate
review), this WP is NOT committed alongside the others -- see the
module-level comment header in `run_motional_al_ion.py`'s own WP35
section.
"""

