    np.testing.assert_allclose(mathieu["mathieu_q"], 0.19127799732774156, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_x"], -0.005884496084657496, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_y"], 0.0023025499448954367, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_z"], 0.0035819461397620595, rtol=1e-9, atol=0)
    assert mathieu["mathieu_q_uncertainty"] == 0.0
    assert mathieu["mathieu_a_x_uncertainty"] == 0.0
    assert mathieu["mathieu_a_y_uncertainty"] == 0.0
    assert mathieu["mathieu_a_z_uncertainty"] == 0.0


