def test_brewer_consistency_check_pinned() -> None:
    """The SECOND, independent dataset (Brewer et al., arXiv:1902.07694,
    a different trap: `ΩRF/2π=40.72 MHz` vs. Marshall's `70.86 MHz`,
    different mode frequencies, same species pair). Generated this
    session: partner-prediction deviations both sub-1%-relative, and the
    per-mode ratios against Brewer's own published `TDS/quantum` row
    (which ALREADY includes intrinsic micromotion per Table S2 footnote
    a) land substantially closer to 1.0 than a plain-participation
    (enhancement=1.0) evaluation would."""
    check = motional_benchmark.run_wp33_brewer_consistency_check()
    np.testing.assert_allclose(
        check.partner_x_relative_deviation, -0.009494145099083643, rtol=1e-6, atol=0
    )
    np.testing.assert_allclose(
        check.partner_y_relative_deviation, -0.007890895963990296, rtol=1e-6, atol=0
    )
    assert abs(check.partner_x_relative_deviation) < 0.01
    assert abs(check.partner_y_relative_deviation) < 0.01

    np.testing.assert_allclose(check.per_mode_ratio_x_com, 0.8990884281035316, rtol=1e-9, atol=0)
    np.testing.assert_allclose(check.per_mode_ratio_x_str, 0.8843495877313101, rtol=1e-9, atol=0)
    np.testing.assert_allclose(check.per_mode_ratio_y_com, 0.8761866378724777, rtol=1e-9, atol=0)
    np.testing.assert_allclose(check.per_mode_ratio_y_str, 0.9324789899879792, rtol=1e-9, atol=0)
    # Every ratio much closer to 1.0 than the un-enhanced (participation-only)
    # ratios would be (all four sit near 0.38-0.49 before enhancement, per
    # this module's own docstring's worked comparison).
    for ratio in (
        check.per_mode_ratio_x_com,
        check.per_mode_ratio_x_str,
        check.per_mode_ratio_y_com,
        check.per_mode_ratio_y_str,
    ):
        assert abs(ratio - 1.0) < 0.2


