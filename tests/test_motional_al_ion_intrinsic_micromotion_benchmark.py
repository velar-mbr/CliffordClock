def test_enhanced_case_per_mode_ratios_improve_over_wp32() -> None:
    """The enhancement-corrected per-mode ratios (predicted/published) land
    substantially closer to 1.0 than WP32's plain-participation ratios for
    every radial mode -- the reconciliation's own central claim, checked
    directly against WP32's own case output (not a hand-copied number),
    so a future engine change that broke this improvement would be caught
    here even if both individual pins were (incorrectly) updated in
    lockstep."""
    enhanced = motional_benchmark.run_motional_al_ion_intrinsic_micromotion_enhanced_case()
    plain = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()

    enhanced_by_name = {m.name: m for m in enhanced.per_mode}
    plain_by_name = {m.name: m for m in plain.per_mode}
    for name in ("x_com", "x_str", "y_com", "y_str"):
        enhanced_ratio = enhanced_by_name[name].ratio_predicted_over_published
        plain_ratio = plain_by_name[name].ratio_predicted_over_published
        assert abs(enhanced_ratio - 1.0) < abs(plain_ratio - 1.0), name

    # Pinned values (this session) for the four radial modes.
    np.testing.assert_allclose(
        enhanced_by_name["x_com"].ratio_predicted_over_published,
        1.0378156224075077,
        rtol=1e-9,
        atol=0,
    )
    np.testing.assert_allclose(
        enhanced_by_name["x_str"].ratio_predicted_over_published,
        0.8594555439542205,
        rtol=1e-9,
        atol=0,
    )
    np.testing.assert_allclose(
        enhanced_by_name["y_com"].ratio_predicted_over_published,
        0.9769728880793773,
        rtol=1e-9,
        atol=0,
    )
    np.testing.assert_allclose(
        enhanced_by_name["y_str"].ratio_predicted_over_published,
        0.9421301941719575,
        rtol=1e-9,
        atol=0,
    )
    # Axial modes are bit-for-bit unchanged from WP31/WP32 (enhancement=1.0).
    np.testing.assert_allclose(
        enhanced_by_name["axial_com"].predicted_shift_per_quantum,
        plain_by_name["axial_com"].predicted_shift_per_quantum,
        rtol=0,
        atol=0,
    )
    np.testing.assert_allclose(
        enhanced_by_name["axial_str"].predicted_shift_per_quantum,
        plain_by_name["axial_str"].predicted_shift_per_quantum,
        rtol=0,
        atol=0,
    )
    assert enhanced_by_name["axial_com"].enhancement == 1.0
    assert enhanced_by_name["axial_str"].enhancement == 1.0


def test_enhanced_case_total_improves_sigma_over_wp32() -> None:
    """The enhancement-corrected TOTAL lands substantially closer to
    Marshall's published band than WP32's own total (~14.0 sigma) --
    pinned this session at `-1.0638483437979477e-17 +/- 3.373e-19`,
    `NOT MET` (the band still does not quite overlap: the residual gap is
    the open item this reconciliation narrows, not fully closes -- see
    the case's own `enhancement_note`), but the deviation itself, checked
    directly, must be much smaller than WP32's own."""
    enhanced = motional_benchmark.run_motional_al_ion_intrinsic_micromotion_enhanced_case()
    plain = motional_benchmark.run_motional_al_ion_radial_reconstructed_case()

    np.testing.assert_allclose(
        enhanced.predicted_total_nominal, -1.0638483437979477e-17, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        enhanced.predicted_total_uncertainty_fractional, 3.3733587425918733e-19, rtol=1e-6, atol=0
    )
    assert enhanced.total_kpi_verdict == "NOT MET"

    published_nominal = -114.6e-19
    enhanced_gap = abs(enhanced.predicted_total_nominal - published_nominal)
    plain_gap = abs(plain.predicted_total_nominal - published_nominal)
    assert enhanced_gap < plain_gap * 0.4  # a large, direct improvement, not a marginal one


