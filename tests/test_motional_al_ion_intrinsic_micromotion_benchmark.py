def test_enhanced_case_clock_mathieu_parameters_pinned() -> None:
    """The clock (Al27+) ion's solved Mathieu parameters for Marshall et
    al.'s trap. Generated by `python benchmarks/run_motional_al_ion.py`
    (this session): `q=0.19127799732774156`, `a_x=-0.005884496084657496`,
    `a_y=0.0023025499448954367`, `a_z=0.0035819461397620595`."""
