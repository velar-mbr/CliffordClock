def test_exact_case_per_mode_ratios_pinned() -> None:
    """The exact-enhancement-corrected per-mode ratios (predicted/
    published), pinned this session, and the structural fact the WP34
    owner asked about directly: the X-axis pair still shows opposite-sign
    deviations from 1.0 (`x_com` above, `x_str` below), essentially
    unchanged from WP33's own leading-order pattern -- confirming a single
    per-axis enhancement factor cannot, by construction, flip the sign of
    a within-axis deviation."""
    case = motional_benchmark.run_motional_al_ion_exact_intrinsic_micromotion_enhanced_case()
    by_name = {m.name: m for m in case.per_mode}

    np.testing.assert_allclose(
        by_name["axial_com"].ratio_predicted_over_published, 1.0070200225419563, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        by_name["axial_str"].ratio_predicted_over_published, 1.0031235055402525, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        by_name["x_com"].ratio_predicted_over_published, 1.035079681823945, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        by_name["x_str"].ratio_predicted_over_published, 0.857189804981225, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        by_name["y_com"].ratio_predicted_over_published, 0.979683066560529, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        by_name["y_str"].ratio_predicted_over_published, 0.9447437170340994, rtol=1e-9, atol=0
    )

    # The structural check itself: X-axis members straddle 1.0, Y-axis
    # members do not.
    x_com_dev = by_name["x_com"].ratio_predicted_over_published - 1.0
    x_str_dev = by_name["x_str"].ratio_predicted_over_published - 1.0
    y_com_dev = by_name["y_com"].ratio_predicted_over_published - 1.0
    y_str_dev = by_name["y_str"].ratio_predicted_over_published - 1.0
    assert x_com_dev * x_str_dev < 0.0
    assert y_com_dev * y_str_dev > 0.0

    # Axial modes are bit-for-bit unchanged from WP31/WP32/WP33 (enhancement=1.0).
    assert by_name["axial_com"].enhancement == 1.0
    assert by_name["axial_str"].enhancement == 1.0

    # Every per-mode entry carries its own nonzero rounding-uncertainty
    # contribution (Part 2 of this WP).
    for mode in case.per_mode:
        assert mode.predicted_shift_per_quantum_rounding_uncertainty > 0.0


def test_exact_case_total_and_both_uncertainty_components_pinned() -> None:
    """The exact-enhancement-corrected TOTAL and its two SEPARATELY
    labeled uncertainty components, pinned this session:
    `-1.063589886484582e-17`, thermometry `+/-3.3682525420067224e-19`,
    rounding `+/-7.32452933997654e-21` (roughly 46x smaller), combined
    `+/-3.369048836057436e-19`, landing at essentially the same deviation
    from Marshall's published band as WP33's own leading-order total
    (`-1.0638483437979477e-17`), `NOT MET`."""
    case = motional_benchmark.run_motional_al_ion_exact_intrinsic_micromotion_enhanced_case()

    np.testing.assert_allclose(
        case.predicted_total_nominal, -1.063589886484582e-17, rtol=1e-9, atol=0
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_nbar_fractional,
        3.3682525420067224e-19,
        rtol=1e-6,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_rounding_fractional,
        7.32452933997654e-21,
        rtol=1e-6,
        atol=0,
    )
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_combined_fractional,
        3.369048836057436e-19,
        rtol=1e-6,
        atol=0,
    )
    # The combined uncertainty is the quadrature sum of the two components,
    # checked directly rather than only pinned.
    expected_combined = (
        case.predicted_total_uncertainty_nbar_fractional**2
        + case.predicted_total_uncertainty_rounding_fractional**2
    ) ** 0.5
    np.testing.assert_allclose(
        case.predicted_total_uncertainty_combined_fractional, expected_combined, rtol=1e-12, atol=0
    )
    # The rounding channel is real (nonzero) but much smaller than the
    # thermometry channel for this dataset.
    assert case.predicted_total_uncertainty_rounding_fractional > 0.0
    assert (
        case.predicted_total_uncertainty_rounding_fractional
        < case.predicted_total_uncertainty_nbar_fractional / 10.0
    )

    assert case.total_kpi_verdict == "NOT MET"

    # Close to WP33's own leading-order total for the same dataset.
    np.testing.assert_allclose(
        case.predicted_total_nominal, -1.0638483437979477e-17, rtol=1e-3, atol=0
    )


