def test_exact_case_clock_mathieu_parameters_pinned() -> None:
    """The clock (Al27+) ion's EXACT solved Mathieu parameters for
    Marshall et al.'s trap. Generated by `python
    benchmarks/run_motional_al_ion.py` (this session):
    `q=0.19008302401903907`, `a_x=-0.005809270371234204`,
    `a_y=0.0022273242314721445`, `a_z=0.0035819461397620595` (the same
    `a_z` as WP33's leading-order solve: exact already, WP34's own
    comment block step 3)."""
    case = motional_benchmark.run_motional_al_ion_exact_intrinsic_micromotion_enhanced_case()
    mathieu = case.clock_mathieu
    np.testing.assert_allclose(mathieu["mathieu_q"], 0.19008302401903907, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_x"], -0.005809270371234204, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_y"], 0.0022273242314721445, rtol=1e-9, atol=0)
    np.testing.assert_allclose(mathieu["mathieu_a_z"], 0.0035819461397620595, rtol=1e-9, atol=0)
    assert mathieu["mathieu_q_uncertainty"] == 0.0

    # WP33's own leading-order solve, reported alongside on the same case
    # record: close (Berkeland's leading-order regime), not identical.
    leading = case.clock_mathieu_leading_order
    np.testing.assert_allclose(leading["mathieu_q"], 0.19127799732774156, rtol=1e-9, atol=0)
    assert leading["mathieu_q"] != mathieu["mathieu_q"]
    assert leading["mathieu_a_z"] == mathieu["mathieu_a_z"]


